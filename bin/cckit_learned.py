#!/usr/bin/env python3
"""Каждая запись в LEARNED.md несёт, насколько хорошо она известна.

Без статуса догадка одной сессии через месяц читается ровно как измеренный
факт — и ассистент, который её прочтёт, тоже не отличит одно от другого.

Линтер принимает ТРИ написания, потому что все три уже лежат на диске в живых
файлах, а не потому, что так гибче:

    **Статус: наблюдение** (2026-09-23, проба ...)   ← чему учит шаблон
    **наблюдение** ...                                ← краткое
    `наблюдение` — 2026-09-23, Opus 5                 ← так пишет живой
                                                        ассистент на этой
                                                        машине

Отвергнуть последнее значило бы отвергнуть единственную честную запись,
которая вообще существует. Формат измерен по файлу, а не придуман.
"""

import os
import re
import sys

STATUSES = ("измерено", "наблюдение", "гипотеза", "слово владельца")

# Заголовок второго уровня начинает запись. `###` сюда не попадает: `#` — не
# пробельный знак, так что `^##\s` его не берёт, и подраздел остаётся частью
# записи, а не становится записью без статуса.
_HEAD = re.compile(r"^##[ \t]+(.+?)[ \t]*$", re.M)

# `**Статус: X**` и `**X**`. Слово «Статус» необязательно — важно, что метка
# выделена, а не что перед ней стоит подпись.
_BOLD = r"\*\*(?:\s*Статус\s*[:\-—]?\s*)?%s\s*\*\*"
# `` `X` `` — только с начала строки (допускается «Статус:» перед ним). В
# середине абзаца обратные кавычки вокруг слова — это цитата слова, а не
# заявление о качестве знания; вводная часть шаблона именно так статусы и
# перечисляет.
_TICK = r"^[ \t]*(?:\*\*)?(?:Статус\s*[:\-—]?\s*)?(?:\*\*)?`%s`"


def records(text):
    """Пары (заголовок, тело). Всё до первого `##` — вводная часть, не запись.

    Отдельная функция, чтобы тест мог утверждать ЧИСЛО разобранных записей:
    линтер, вернувший пустой список оттого, что не нашёл ни одной записи,
    выглядит точно так же, как линтер на чистом файле.
    """
    heads = list(_HEAD.finditer(text or ""))
    out = []
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        out.append((m.group(1).strip(), text[m.end():end]))
    return out


def _status_of(body):
    for s in STATUSES:
        pat = re.escape(s)
        if re.search(_BOLD % pat, body) or re.search(_TICK % pat, body, re.M):
            return s
    return None


def _invented(body):
    """Что автор ПЫТАЛСЯ объявить статусом, если это не статус.

    Сообщение «нет статуса» на записи с `**Статус: наверное**` отправляет
    искать пропажу там, где её нет.
    """
    m = re.search(r"\*\*\s*Статус\s*[:\-—]?\s*([^*]{1,40}?)\s*\*\*", body)
    return m.group(1) if m else None


def lint(text):
    """По сообщению на каждую запись без статуса. Пустой список — чисто."""
    msgs = []
    for title, body in records(text):
        if _status_of(body):
            continue
        bad = _invented(body)
        if bad:
            msgs.append("«%s» — «%s» не статус. Есть только: %s"
                        % (title, bad, ", ".join(STATUSES)))
        else:
            msgs.append("«%s» — нет статуса. Ожидается один из: %s"
                        % (title, ", ".join(STATUSES)))
    return msgs


def cmd_lint(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    msgs = lint(text)
    print("%s: записей %d" % (path, len(records(text))))
    for m in msgs:
        print("  " + m)
    if msgs:
        print("\nЗапись без статуса через месяц читается как измеренный факт.")
        return 1
    print("  все записи со статусом")
    return 0


def main(argv):
    if not argv:
        sys.stderr.write("нужен путь: cckit_learned.py <LEARNED.md> [ещё...]\n")
        return 2
    rc = 0
    for p in argv:
        if not os.path.exists(p):
            sys.stderr.write("нет файла: %s\n" % p)
            rc = 2
            continue
        rc = max(rc, cmd_lint(p))
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
